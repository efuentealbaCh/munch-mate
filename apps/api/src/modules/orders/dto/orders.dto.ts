/** Area of a zone: its vertices (3–200, validated by the service with geoAreaProblem). */
const AREA = [
  IsOptional(),
  ValidateIf((_: unknown, value: unknown) => value !== null),
  IsArray(),
  ArrayMaxSize(GEO_LIMITS.zoneVerticesMax),
  ValidateNested({ each: true }),
  Type(() => GeoPointDto),
];

