import type { PaymentMethod, TablePaymentItem, TablePaymentKind, TableSplit } from "@app/types";
import { Injectable } from "@nestjs/common";
import { InjectModel } from "@nestjs/mongoose";
import { type ClientSession, type Model, Types } from "mongoose";
import { TableSession } from "./schemas/table-session.schema";

export interface TableSessionRecord {
  id: string;
  restaurantId: string;
  tableId: string;
  tableLabel: string;
  status: "open" | "closed";
  openedAt: Date;
  waiterCalledAt: Date | null;
  billRequestedAt: Date | null;
  requestedTip: number | null;
  closedAt: Date | null;
  closedBusinessDate: string | null;
  tip: number | null;
  paymentMethod: PaymentMethod | null;
  paymentMethods: PaymentMethod[];
  closedByName: string | null;
  split: TableSplit | null;
  payments: TablePaymentRecord[];
  /** Optimistic concurrency of payments (see the schema). */
  revision: number;
}

export interface TablePaymentRecord {
  id: string;
  kind: TablePaymentKind;
  amount: number;
  tip: number;
  method: PaymentMethod;
  part: number | null;
  items: TablePaymentItem[];
  at: Date;
  byUserId: string;
  byName: string | null;
}

/** A payment about to be recorded (its id is generated by the repository). */
export type NewTablePayment = Omit<TablePaymentRecord, "id">;

/** What closing an account writes. */
export interface CloseChange {
  tip: number;
  paymentMethod: PaymentMethod | null;
  paymentMethods: PaymentMethod[];
  byUserId: string;
  byName: string | null;
  businessDate: string;
}

const oid = (id: string) => new Types.ObjectId(id);
const DUPLICATE_KEY = 11000;

/** Tenant-scoped: every method takes the restaurant id first and filters by it. */
@Injectable()
export class TableSessionsRepository {
  constructor(@InjectModel(TableSession.name) private readonly sessions: Model<TableSession>) {}

  /**
   * The open account of a table, opening one when there is none. Two first orders of the same table at the
   * same time end up in the same account: the unique index lets one insert win and the other reads it.
   */
  async getOrOpen(
    restaurantId: string,
    table: { id: string; label: string },
    session?: ClientSession,
  ): Promise<TableSessionRecord> {
    const filter = { restaurantId: oid(restaurantId), tableId: oid(table.id), status: "open" as const };
    try {
      const doc = await this.sessions
        .findOneAndUpdate(
          filter,
          { $setOnInsert: { tableLabel: table.label, openedAt: new Date() } },
          { upsert: true, returnDocument: "after", session },
        )
        .lean();
      return toRecord(doc!);
    } catch (error) {
      if ((error as { code?: number }).code !== DUPLICATE_KEY) throw error;
      const doc = await this.sessions.findOne(filter, null, { session }).lean();
      if (!doc) throw error;
      return toRecord(doc);
    }
  }

  async findOpenByTable(restaurantId: string, tableId: string): Promise<TableSessionRecord | null> {
    const doc = await this.sessions.findOne({ restaurantId: oid(restaurantId), tableId: oid(tableId), status: "open" }).lean();
    return doc ? toRecord(doc) : null;
  }

  /** The table's latest account closed after `since` (the customer's phone shows "pagada" for a while). */
  async findRecentlyClosedByTable(restaurantId: string, tableId: string, since: Date): Promise<TableSessionRecord | null> {
    const doc = await this.sessions
      .findOne({ restaurantId: oid(restaurantId), tableId: oid(tableId), status: "closed", closedAt: { $gte: since } })
      .sort({ closedAt: -1 })
      .lean();
    return doc ? toRecord(doc) : null;
  }

  async findOne(restaurantId: string, sessionId: string): Promise<TableSessionRecord | null> {
    if (!Types.ObjectId.isValid(sessionId)) return null;
    const doc = await this.sessions.findOne({ _id: oid(sessionId), restaurantId: oid(restaurantId) }).lean();
    return doc ? toRecord(doc) : null;
  }

  /** Open accounts, oldest first (the floor). */
  async listOpen(restaurantId: string): Promise<TableSessionRecord[]> {
    const docs = await this.sessions.find({ restaurantId: oid(restaurantId), status: "open" }).sort({ openedAt: 1 }).lean();
    return docs.map(toRecord);
  }

  /** Accounts closed on business days from..to (inclusive): their tips. */
  async listClosedBetween(restaurantId: string, from: string, to: string): Promise<TableSessionRecord[]> {
    const docs = await this.sessions
      .find({ restaurantId: oid(restaurantId), status: "closed", closedBusinessDate: { $gte: from, $lte: to } })
      .lean();
    return docs.map(toRecord);
  }

  /** "Llamar al garzón": only the first call counts until someone attends. @returns null if not open. */
  async callWaiter(restaurantId: string, sessionId: string): Promise<TableSessionRecord | null> {
    // Only the first call stamps the time (the oldest call is attended first); later ones change nothing.
    await this.stampOnce(restaurantId, sessionId, "waiterCalledAt");
    return this.findOpen(restaurantId, sessionId);
  }

  /** The customer asks for the bill with a tip; asking again updates the tip. @returns null if not open. */
  async requestBill(restaurantId: string, sessionId: string, requestedTip: number): Promise<TableSessionRecord | null> {
    await this.stampOnce(restaurantId, sessionId, "billRequestedAt");
    return this.updateOpen(restaurantId, sessionId, { $set: { requestedTip } });
  }

  /** Sets a call timestamp only while it is empty (two phones pressing at once keep the first time). */
  private async stampOnce(restaurantId: string, sessionId: string, field: "waiterCalledAt" | "billRequestedAt"): Promise<void> {
    if (!Types.ObjectId.isValid(sessionId)) return;
    await this.sessions.updateOne(
      { _id: oid(sessionId), restaurantId: oid(restaurantId), status: "open", [field]: null },
      { $set: { [field]: new Date() } },
    );
  }

  private async findOpen(restaurantId: string, sessionId: string): Promise<TableSessionRecord | null> {
    if (!Types.ObjectId.isValid(sessionId)) return null;
    const doc = await this.sessions.findOne({ _id: oid(sessionId), restaurantId: oid(restaurantId), status: "open" }).lean();
    return doc ? toRecord(doc) : null;
  }

  /** A waiter attended the call (or the bill request). @returns null if not open. */
  async attend(restaurantId: string, sessionId: string, kind: "waiter" | "bill"): Promise<TableSessionRecord | null> {
    return this.updateOpen(restaurantId, sessionId, {
      $set: kind === "waiter" ? { waiterCalledAt: null } : { billRequestedAt: null },
    });
  }

  /**
   * Records a payment and/or closes the account, only if it is still open and on the revision the payment was
   * computed on (two waiters charging at once: the second write misses instead of exceeding the bill).
   * @param payment null closes without a new payment (everything was already paid).
   * @param close null records a partial payment and leaves the account open.
   * @returns The updated account, or null if it closed or changed in between.
   */
  async charge(
    restaurantId: string,
    sessionId: string,
    expectedRevision: number,
    payment: NewTablePayment | null,
    close: CloseChange | null,
    session?: ClientSession,
  ): Promise<TableSessionRecord | null> {
    if (!Types.ObjectId.isValid(sessionId)) return null;
    const doc = await this.sessions
      .findOneAndUpdate(
        { _id: oid(sessionId), restaurantId: oid(restaurantId), status: "open", ...revisionFilter(expectedRevision) },
        {
          $inc: { revision: 1 },
          ...(payment ? { $push: { payments: toPaymentDoc(payment) } } : {}),
          ...(close
            ? {
                $set: {
                  status: "closed",
                  closedAt: new Date(),
                  closedBusinessDate: close.businessDate,
                  tip: close.tip,
                  paymentMethod: close.paymentMethod,
                  paymentMethods: close.paymentMethods,
                  closedBy: oid(close.byUserId),
                  closedByName: close.byName,
                  waiterCalledAt: null,
                  billRequestedAt: null,
                },
              }
            : {}),
        },
        { returnDocument: "after", session },
      )
      .lean();
    return doc ? toRecord(doc) : null;
  }

  /**
   * Deletes a payment of an open account. Not conditional on the revision (deleting does not depend on what
   * was computed), but it bumps it, so a payment computed before the deletion is not recorded after it.
   * @returns The updated account, or null if it is not open or the payment is not there any more.
   */
  async deletePayment(restaurantId: string, sessionId: string, paymentId: string): Promise<TableSessionRecord | null> {
    if (!Types.ObjectId.isValid(sessionId) || !Types.ObjectId.isValid(paymentId)) return null;
    const doc = await this.sessions
      .findOneAndUpdate(
        { _id: oid(sessionId), restaurantId: oid(restaurantId), status: "open", "payments._id": oid(paymentId) },
        { $pull: { payments: { _id: oid(paymentId) } }, $inc: { revision: 1 } },
        { returnDocument: "after" },
      )
      .lean();
    return doc ? toRecord(doc) : null;
  }

  /**
   * Sets (or with null removes) the split plan of an open account, on the revision it was checked against.
   * @returns The updated account, or null if it closed or changed in between.
   */
  async setSplit(
    restaurantId: string,
    sessionId: string,
    expectedRevision: number,
    split: TableSplit | null,
  ): Promise<TableSessionRecord | null> {
    if (!Types.ObjectId.isValid(sessionId)) return null;
    const doc = await this.sessions
      .findOneAndUpdate(
        { _id: oid(sessionId), restaurantId: oid(restaurantId), status: "open", ...revisionFilter(expectedRevision) },
        {
          $set: { split: split ? { mode: split.mode, parts: split.mode === "equal" ? split.parts : null } : null },
          $inc: { revision: 1 },
        },
        { returnDocument: "after" },
      )
      .lean();
    return doc ? toRecord(doc) : null;
  }

  /**
   * Before changing what one of its orders costs or how it was paid (item edits, paying an order on its own):
   * bumps the account's revision only while it has no payments, inside the caller's transaction. A payment
   * computed meanwhile then misses (TABLE_SESSION_CHANGED), and a payment recorded first makes this miss.
   * @returns false when the account has payments (or does not exist).
   */
  async lockWithoutPayments(restaurantId: string, sessionId: string, session: ClientSession): Promise<boolean> {
    if (!Types.ObjectId.isValid(sessionId)) return false;
    const doc = await this.sessions
      .findOneAndUpdate(
        { _id: oid(sessionId), restaurantId: oid(restaurantId), "payments.0": { $exists: false } },
        { $inc: { revision: 1 } },
        { returnDocument: "after", session },
      )
      .lean();
    return doc !== null;
  }

  private async updateOpen(
    restaurantId: string,
    sessionId: string,
    update: Record<string, unknown>,
    session?: ClientSession,
  ): Promise<TableSessionRecord | null> {
    if (!Types.ObjectId.isValid(sessionId)) return null;
    const doc = await this.sessions
      .findOneAndUpdate({ _id: oid(sessionId), restaurantId: oid(restaurantId), status: "open" }, update, {
        returnDocument: "after",
        session,
      })
      .lean();
    return doc ? toRecord(doc) : null;
  }
}

type SessionDoc = TableSession & { _id: Types.ObjectId };

/** Accounts older than split bills have no revision: it reads as 0. */
const revisionFilter = (revision: number) => ({ revision: revision === 0 ? { $in: [0, null] } : revision });

const toPaymentDoc = (payment: NewTablePayment) => ({
  ...payment,
  _id: new Types.ObjectId(),
  byUserId: oid(payment.byUserId),
  items: payment.items.map((item) => ({ ...item, orderId: oid(item.orderId) })),
});

function toSplit(split: TableSession["split"] | undefined): TableSplit | null {
  if (!split) return null;
  if (split.mode === "equal") return { mode: "equal", parts: split.parts ?? 2 };
  return { mode: split.mode };
}

function toRecord(doc: SessionDoc): TableSessionRecord {
  return {
    id: doc._id.toString(),
    restaurantId: doc.restaurantId.toString(),
    tableId: doc.tableId.toString(),
    tableLabel: doc.tableLabel,
    status: doc.status,
    openedAt: doc.openedAt,
    waiterCalledAt: doc.waiterCalledAt ?? null,
    billRequestedAt: doc.billRequestedAt ?? null,
    requestedTip: doc.requestedTip ?? null,
    closedAt: doc.closedAt ?? null,
    closedBusinessDate: doc.closedBusinessDate ?? null,
    tip: doc.tip ?? null,
    paymentMethod: doc.paymentMethod ?? null,
    // Accounts closed before split bills: their single method.
    paymentMethods: doc.paymentMethods?.length ? [...doc.paymentMethods] : doc.paymentMethod ? [doc.paymentMethod] : [],
    closedByName: doc.closedByName ?? null,
    split: toSplit(doc.split),
    payments: (doc.payments ?? []).map((payment) => ({
      id: payment._id.toString(),
      kind: payment.kind,
      amount: payment.amount,
      tip: payment.tip,
      method: payment.method,
      part: payment.part ?? null,
      items: (payment.items ?? []).map((item) => ({ orderId: item.orderId.toString(), line: item.line, quantity: item.quantity })),
      at: payment.at,
      byUserId: payment.byUserId.toString(),
      byName: payment.byName ?? null,
    })),
    revision: doc.revision ?? 0,
  };
}
