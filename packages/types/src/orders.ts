  paymentBreakdown: PaymentPortion[];
  items: OrderItemView[];
  subtotal: number;
  total: number;
  currency: string;
  customerName: string;
  /** Pickup and delivery; "" for dine-in. */
  customerPhone: string;
  customerEmail: string;
  note: string;
